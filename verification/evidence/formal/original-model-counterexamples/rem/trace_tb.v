  reg genclock = 1;
  reg [31:0] cycle = 0;
  formal_execute_m UUT (

  );
`ifndef VERILATOR
  initial begin
    if ($value$plusargs("vcd=%s", vcdfile)) begin
      $dumpfile(vcdfile);
